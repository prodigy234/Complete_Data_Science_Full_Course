DROP DATABASE IF EXISTS novamart;
CREATE DATABASE novamart CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE novamart;

-- =====================================================================
-- SECTION 1: TABLE DEFINITIONS
-- =====================================================================

CREATE TABLE regions (
    region_id    INT          PRIMARY KEY,
    region_name  VARCHAR(50)  NOT NULL UNIQUE
) ENGINE=InnoDB;

CREATE TABLE departments (
    department_id    INT          PRIMARY KEY,
    department_name  VARCHAR(60)  NOT NULL UNIQUE,
    location         VARCHAR(60)
) ENGINE=InnoDB;

CREATE TABLE salary_grades (
    grade_id    INT          PRIMARY KEY,
    grade_name  VARCHAR(30)  NOT NULL,
    min_salary  DECIMAL(10,2) NOT NULL,
    max_salary  DECIMAL(10,2) NOT NULL
) ENGINE=InnoDB;

CREATE TABLE stores (
    store_id     INT          PRIMARY KEY,
    store_name   VARCHAR(80)  NOT NULL,
    city         VARCHAR(50)  NOT NULL,
    region_id    INT          NOT NULL,
    opened_date  DATE         NOT NULL,
    CONSTRAINT fk_stores_region FOREIGN KEY (region_id) REFERENCES regions(region_id)
) ENGINE=InnoDB;

CREATE TABLE employees (
    employee_id    INT           PRIMARY KEY,
    first_name     VARCHAR(50)   NOT NULL,
    last_name      VARCHAR(50)   NOT NULL,
    email          VARCHAR(100)  NOT NULL UNIQUE,
    hire_date      DATE          NOT NULL,
    job_title      VARCHAR(60)   NOT NULL,
    salary         DECIMAL(10,2) NOT NULL CHECK (salary > 0),
    department_id  INT           NOT NULL,
    manager_id     INT           NULL,
    store_id       INT           NULL,
    CONSTRAINT fk_emp_dept    FOREIGN KEY (department_id) REFERENCES departments(department_id),
    CONSTRAINT fk_emp_manager FOREIGN KEY (manager_id)    REFERENCES employees(employee_id),
    CONSTRAINT fk_emp_store   FOREIGN KEY (store_id)      REFERENCES stores(store_id)
) ENGINE=InnoDB;

CREATE TABLE categories (
    category_id         INT          PRIMARY KEY,
    category_name       VARCHAR(60)  NOT NULL,
    parent_category_id  INT          NULL,
    CONSTRAINT fk_cat_parent FOREIGN KEY (parent_category_id) REFERENCES categories(category_id)
) ENGINE=InnoDB;

CREATE TABLE suppliers (
    supplier_id    INT           PRIMARY KEY,
    supplier_name  VARCHAR(80)   NOT NULL,
    contact_email  VARCHAR(100),
    country        VARCHAR(50),
    rating         DECIMAL(2,1)  CHECK (rating BETWEEN 0 AND 5)
) ENGINE=InnoDB;

CREATE TABLE products (
    product_id    INT            PRIMARY KEY,
    product_name  VARCHAR(100)   NOT NULL,
    sku           VARCHAR(20)    NOT NULL UNIQUE,
    category_id   INT            NOT NULL,
    supplier_id   INT            NOT NULL,
    unit_price    DECIMAL(10,2)  NOT NULL CHECK (unit_price >= 0),
    unit_cost     DECIMAL(10,2)  NOT NULL CHECK (unit_cost >= 0),
    launch_date   DATE,
    discontinued  TINYINT(1)     NOT NULL DEFAULT 0,
    CONSTRAINT fk_prod_cat      FOREIGN KEY (category_id) REFERENCES categories(category_id),
    CONSTRAINT fk_prod_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers(supplier_id)
) ENGINE=InnoDB;

CREATE TABLE promotions (
    promo_id      INT           PRIMARY KEY,
    promo_code    VARCHAR(30)   NOT NULL UNIQUE,
    discount_pct  DECIMAL(5,2)  NOT NULL,
    start_date    DATE          NOT NULL,
    end_date      DATE          NOT NULL
) ENGINE=InnoDB;

CREATE TABLE customers (
    customer_id   INT           PRIMARY KEY,
    first_name    VARCHAR(50)   NOT NULL,
    last_name     VARCHAR(50)   NOT NULL,
    email         VARCHAR(100)  NOT NULL UNIQUE,
    phone         VARCHAR(25)   NULL,
    gender        CHAR(1),
    birth_date    DATE,
    city          VARCHAR(50),
    country       VARCHAR(50),
    region_id     INT           NOT NULL,
    signup_date   DATE          NOT NULL,
    loyalty_tier  ENUM('Bronze','Silver','Gold','Platinum') NOT NULL DEFAULT 'Bronze',
    CONSTRAINT fk_cust_region FOREIGN KEY (region_id) REFERENCES regions(region_id)
) ENGINE=InnoDB;

CREATE TABLE inventory (
    store_id          INT NOT NULL,
    product_id        INT NOT NULL,
    quantity_on_hand  INT NOT NULL DEFAULT 0,
    reorder_level     INT NOT NULL DEFAULT 10,
    PRIMARY KEY (store_id, product_id),
    CONSTRAINT fk_inv_store   FOREIGN KEY (store_id)   REFERENCES stores(store_id),
    CONSTRAINT fk_inv_product FOREIGN KEY (product_id) REFERENCES products(product_id)
) ENGINE=InnoDB;

CREATE TABLE orders (
    order_id      INT            PRIMARY KEY,
    customer_id   INT            NOT NULL,
    store_id      INT            NULL COMMENT 'NULL = online order',
    employee_id   INT            NULL COMMENT 'sales associate for in-store orders',
    promo_id      INT            NULL,
    order_date    DATE           NOT NULL,
    order_status  ENUM('Processing','Shipped','Delivered','Cancelled','Returned') NOT NULL,
    channel       ENUM('Online','In-Store') NOT NULL,
    total_amount  DECIMAL(12,2)  NOT NULL,
    CONSTRAINT fk_ord_cust  FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
    CONSTRAINT fk_ord_store FOREIGN KEY (store_id)    REFERENCES stores(store_id),
    CONSTRAINT fk_ord_emp   FOREIGN KEY (employee_id) REFERENCES employees(employee_id),
    CONSTRAINT fk_ord_promo FOREIGN KEY (promo_id)    REFERENCES promotions(promo_id)
) ENGINE=InnoDB;

CREATE TABLE order_items (
    order_item_id  INT            PRIMARY KEY,
    order_id       INT            NOT NULL,
    product_id     INT            NOT NULL,
    quantity       INT            NOT NULL CHECK (quantity > 0),
    unit_price     DECIMAL(10,2)  NOT NULL,
    discount_pct   DECIMAL(5,2)   NOT NULL DEFAULT 0,
    CONSTRAINT fk_oi_order   FOREIGN KEY (order_id)   REFERENCES orders(order_id) ON DELETE CASCADE,
    CONSTRAINT fk_oi_product FOREIGN KEY (product_id) REFERENCES products(product_id)
) ENGINE=InnoDB;

CREATE TABLE payments (
    payment_id      INT            PRIMARY KEY,
    order_id        INT            NOT NULL,
    payment_date    DATE           NULL,
    payment_method  ENUM('Credit Card','Debit Card','Bank Transfer','Mobile Money','PayPal','Cash') NOT NULL,
    amount          DECIMAL(12,2)  NOT NULL,
    payment_status  ENUM('Paid','Pending','Failed','Refunded') NOT NULL,
    CONSTRAINT fk_pay_order FOREIGN KEY (order_id) REFERENCES orders(order_id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE shipments (
    shipment_id      INT          PRIMARY KEY,
    order_id         INT          NOT NULL,
    carrier          VARCHAR(40)  NOT NULL,
    shipped_date     DATE         NOT NULL,
    delivered_date   DATE         NULL,
    shipment_status  ENUM('In Transit','Delivered') NOT NULL,
    CONSTRAINT fk_ship_order FOREIGN KEY (order_id) REFERENCES orders(order_id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE reviews (
    review_id    INT           PRIMARY KEY,
    product_id   INT           NOT NULL,
    customer_id  INT           NOT NULL,
    rating       TINYINT       NOT NULL CHECK (rating BETWEEN 1 AND 5),
    review_text  VARCHAR(300)  NULL,
    review_date  DATE          NOT NULL,
    CONSTRAINT fk_rev_product FOREIGN KEY (product_id)  REFERENCES products(product_id),
    CONSTRAINT fk_rev_cust    FOREIGN KEY (customer_id) REFERENCES customers(customer_id)
) ENGINE=InnoDB;

CREATE INDEX idx_orders_date     ON orders(order_date);
CREATE INDEX idx_orders_customer ON orders(customer_id);
CREATE INDEX idx_items_product   ON order_items(product_id);


